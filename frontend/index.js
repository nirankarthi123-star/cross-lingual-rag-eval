const API_BASE = window.location.origin;
let chatHistory = [];
let selectedIdx = null;

const historyEl = document.getElementById('chat-history');
const formEl = document.getElementById('chat-form');
const inputEl = document.getElementById('query-input');
const sendBtn = document.getElementById('send-btn');
const clearBtn = document.getElementById('clear-btn');
const mitigationToggle = document.getElementById('mitigation-toggle');
const sidebar = document.getElementById('eval-sidebar');
const sidebarToggle = document.getElementById('sidebar-toggle');
const sidebarOpenBtn = document.getElementById('sidebar-open-btn');

// --- Sidebar toggle ---
sidebarToggle.addEventListener('click', () => {
    sidebar.classList.add('collapsed');
    sidebar.classList.remove('open');
    sidebarOpenBtn.style.display = 'block';
});
sidebarOpenBtn.addEventListener('click', () => {
    sidebar.classList.remove('collapsed');
    sidebar.classList.add('open');
    sidebarOpenBtn.style.display = 'none';
});

// --- Mitigation toggle ---
mitigationToggle.addEventListener('change', () => {
    mitigationToggle.parentElement.querySelector('span').textContent =
        mitigationToggle.checked ? 'Mitigation ON' : 'Mitigation OFF';
});

// --- Clear chat ---
clearBtn.addEventListener('click', () => {
    if (chatHistory.length > 0 && !confirm('Clear chat history?')) return;
    chatHistory = [];
    selectedIdx = null;
    historyEl.innerHTML = buildWelcomeHTML();
    attachChipListeners();
    renderSidebar(null);
});

// --- Prompt chips ---
function attachChipListeners() {
    document.querySelectorAll('.chip').forEach(chip => {
        chip.addEventListener('click', () => {
            inputEl.value = chip.dataset.query;
            formEl.dispatchEvent(new Event('submit'));
        });
    });
}
attachChipListeners();

function buildWelcomeHTML() {
    return `
        <div class="welcome-msg">
            <h2>Ask a question</h2>
            <p>Chat with the ingested document corpus. Answers are retrieved from the FAISS index, generated by the LLM, and evaluated for faithfulness in real time.</p>
            <div class="prompt-chips">
                <button class="chip" data-query="How do I activate international roaming on my mobile postpaid connection?">How to activate international roaming?</button>
                <button class="chip" data-query="Ennoda mobile postpaid connection-la international roaming eppadi activate panrathu?">Tamil-English: Activate roaming</button>
                <button class="chip" data-query="Mere mobile postpaid connection par international roaming kaise activate karu?">Hindi-English: Activate roaming</button>
                <button class="chip" data-query="What is the capital of Mars?">Out-of-context question</button>
            </div>
        </div>
    `;
}

// --- Textarea handling ---
inputEl.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
        e.preventDefault();
        formEl.dispatchEvent(new Event('submit'));
    }
});

// Auto-resize textarea
inputEl.addEventListener('input', () => {
    inputEl.style.height = 'auto';
    inputEl.style.height = Math.min(inputEl.scrollHeight, 140) + 'px';
});

// --- Submit ---
formEl.addEventListener('submit', async (e) => {
    e.preventDefault();
    const query = inputEl.value.trim();
    if (!query) return;
    inputEl.value = '';
    inputEl.style.height = 'auto';

    const welcome = historyEl.querySelector('.welcome-msg');
    if (welcome) welcome.remove();

    addMessage('user', query);

    const loadingEl = document.createElement('div');
    loadingEl.className = 'msg-loading';
    loadingEl.innerHTML = '<div class="dot"></div><div class="dot"></div><div class="dot"></div>';
    historyEl.appendChild(loadingEl);
    historyEl.scrollTop = historyEl.scrollHeight;
    sendBtn.disabled = true;

    try {
        const res = await fetch(`${API_BASE}/api/chat`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                query,
                mitigation_enabled: mitigationToggle.checked,
            }),
        });
        const data = await res.json();
        loadingEl.remove();

        if (data.error || !res.ok) {
            addMessage('error', `Error: ${data.error || data.detail || 'Unknown error'}`, data);
        } else {
            addMessage('bot', data.answer, data);
        }
    } catch (err) {
        loadingEl.remove();
        addMessage('error', 'Network error or server unreachable.');
    }

    sendBtn.disabled = false;
    inputEl.focus();
});

// --- Message rendering ---
function addMessage(role, text, data = null) {
    const idx = chatHistory.length;

    const msgDiv = document.createElement('div');
    msgDiv.className = `msg msg-${role}`;
    msgDiv.dataset.idx = idx;

    if (role === 'bot' && window.marked) {
        msgDiv.innerHTML = window.marked.parse(text);
    } else {
        msgDiv.textContent = text;
    }

    historyEl.appendChild(msgDiv);
    historyEl.scrollTop = historyEl.scrollHeight;

    chatHistory.push({ role, text, data });

    if ((role === 'bot' || role === 'error') && data) {
        msgDiv.style.cursor = 'pointer';
        msgDiv.title = 'Click to view evaluation';
        msgDiv.addEventListener('click', () => selectMessage(idx));
        // Auto-select the latest bot message
        selectMessage(idx);
    }
}

function selectMessage(idx) {
    selectedIdx = idx;
    document.querySelectorAll('.msg').forEach(m => m.classList.remove('selected'));
    const el = document.querySelector(`.msg[data-idx="${idx}"]`);
    if (el) el.classList.add('selected');

    const entry = chatHistory[idx];
    if (entry && entry.data) {
        renderSidebar(entry.data);
    }
}

// --- Sidebar rendering ---
function escapeHtml(unsafe) {
    if (!unsafe) return '';
    return unsafe
         .replace(/&/g, '&amp;')
         .replace(/</g, '&lt;')
         .replace(/>/g, '&gt;')
         .replace(/"/g, '&quot;')
         .replace(/'/g, '&#039;');
}

function renderSidebar(data) {
    const content = document.getElementById('sidebar-content');
    const empty = document.getElementById('sidebar-empty');

    if (!data) {
        empty.classList.remove('hidden');
        content.classList.add('hidden');
        return;
    }

    empty.classList.add('hidden');
    content.classList.remove('hidden');

    let html = `<div style="font-size:0.9rem;">`;

    // Summary metrics
    html += metricRow('Faithfulness', data.faithfulness_score !== null && data.faithfulness_score !== undefined ? data.faithfulness_score.toFixed(3) : 'N/A');
    html += metricRow('Hallucination',
        `<span style="color:${data.hallucination_flag ? 'var(--error)' : 'var(--success)'}; font-weight:600;">${data.hallucination_flag ? 'FAIL' : 'PASS'}</span>`
    , true);
    html += metricRow('Code-Mix', data.code_mix_detected ? 'Yes' : 'No');
    html += metricRow('Language(s)', (data.detected_languages || []).join(', '));
    html += metricRow('Mitigation', data.mitigation_applied ? 'Applied' : (data.mitigation_enabled ? 'Enabled (not needed)' : 'Disabled'));
    html += metricRow('Latency', data.latency + 's');
    html += `</div>`;

    // Normalized query
    if (data.normalized_query) {
        html += section('Normalized Query',
            `<div style="background:#f1f5f9; padding:10px; border-radius:6px; font-size:0.85rem; color:#334155;">${escapeHtml(data.normalized_query)}</div>`
        );
    }

    // Judge explanation
    if (data.faithfulness_explanation) {
        html += section('Judge Explanation',
            `<div style="background:#f8fafc; padding:10px; border-radius:6px; font-size:0.82rem; color:#475569; border:1px dashed #cbd5e1; white-space:pre-wrap; max-height:160px; overflow-y:auto;">${escapeHtml(data.faithfulness_explanation)}</div>`
        );
    }

    // Sources (collapsible cards)
    if (data.retrieved_documents && data.retrieved_documents.length > 0) {
        html += `<div style="margin-top:18px; font-weight:600; font-size:0.88rem; color:var(--text-muted); margin-bottom:10px;">Sources (${data.retrieved_documents.length})</div>`;
        data.retrieved_documents.forEach((doc, i) => {
            const snippet = doc.text ? doc.text.substring(0, 120) : '';
            html += `
                <details style="border:1px solid var(--border); border-radius:6px; margin-bottom:8px; overflow:hidden;">
                    <summary style="padding:10px; background:#f8fafc; font-size:0.82rem; cursor:pointer; display:flex; justify-content:space-between; align-items:center;">
                        <span style="font-weight:600; color:#334155;">Source ${i+1}</span>
                        <span style="color:var(--primary); font-weight:600; font-size:0.8rem;">${(doc.score || 0).toFixed(3)}</span>
                    </summary>
                    <div style="padding:10px; font-size:0.82rem; border-top:1px solid var(--border);">
                        <div style="color:var(--text-muted); font-size:0.78rem; margin-bottom:6px;">
                            Doc: ${escapeHtml(doc.document_id)} &middot; Chunk: ${escapeHtml(doc.chunk_id)}
                        </div>
                        <div style="color:#1e293b; line-height:1.5;">${escapeHtml(doc.text)}</div>
                    </div>
                </details>
            `;
        });
    } else {
        html += `<div style="margin-top:18px; font-size:0.82rem; color:var(--text-muted);">No documents retrieved.</div>`;
    }

    // Model info
    html += `
        <div style="margin-top:16px; padding-top:12px; border-top:1px solid var(--border); font-size:0.78rem; color:var(--text-muted); line-height:1.7;">
            Generator: ${escapeHtml(data.generator_model || 'Unknown')}<br/>
            Judge: ${escapeHtml(data.judge_model || 'Unknown')}
        </div>
    `;

    content.innerHTML = html;
}

function metricRow(label, value, isHtml = false) {
    return `
        <div style="display:flex; justify-content:space-between; align-items:center; padding:6px 0; border-bottom:1px solid #f1f5f9;">
            <span style="color:var(--text-muted); font-weight:500;">${label}</span>
            <span style="font-weight:600; font-size:0.88rem;">${isHtml ? value : escapeHtml(String(value))}</span>
        </div>
    `;
}

function section(title, content) {
    return `
        <div style="margin-top:16px; padding-top:12px; border-top:1px solid var(--border);">
            <div style="font-weight:600; font-size:0.82rem; color:var(--text-muted); margin-bottom:8px;">${title}</div>
            ${content}
        </div>
    `;
}
